fruits = ["apple", "banana", "mango"]

fruits.append("orange")
print(fruits)


fruits.append("pineapple")
print(fruits)


fruits.insert(4, "cat")
print(fruits)


fruits.pop()
print(fruits, "pop")


fruits.sort()
print(fruits, "sorting")

fruits.reverse()
print(fruits, "reverse")


fruits.clear()
print(fruits, "clear")